"""Local persistence. Never load untrusted joblib model files."""
from __future__ import annotations

import json
import os
from pathlib import Path
import tempfile

import joblib

from .model import CaRSELClassifier


def model_path() -> Path:
    return Path(os.environ.get("CARSEL_MODEL_PATH", "artifacts/carsel_model.joblib"))


def report_path(path: Path) -> Path:
    return path.with_suffix(".report.json")


def save_artifacts(model: CaRSELClassifier, report: dict, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replacement prevents another request from loading a partial artifact.
    with tempfile.NamedTemporaryFile(dir=path.parent, suffix=".joblib", delete=False) as temp:
        staging_model = Path(temp.name)
    with tempfile.NamedTemporaryFile(dir=path.parent, suffix=".json", delete=False) as temp:
        staging_report = Path(temp.name)
    try:
        joblib.dump(model, staging_model, compress=3)
        staging_report.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        os.replace(staging_model, path)
        os.replace(staging_report, report_path(path))
    finally:
        staging_model.unlink(missing_ok=True)
        staging_report.unlink(missing_ok=True)


def load_model(path: Path) -> CaRSELClassifier:
    # joblib is pickle-based. Only use artifacts generated by the trusted training process.
    result = joblib.load(path)
    if not isinstance(result, CaRSELClassifier):
        raise TypeError("Expected a CaRSELClassifier model artifact")
    return result


def load_report(path: Path) -> dict | None:
    rp = report_path(path)
    return json.loads(rp.read_text(encoding="utf-8")) if rp.exists() else None


def _registry_dir(active_model: Path) -> Path:
    return Path(active_model).parent / "registry"


def archive_run(model: CaRSELClassifier, report: dict, active_model: Path) -> str:
    """Archive model and report together under server-generated names."""
    from datetime import datetime, timezone
    import uuid
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    run_id = f"run-{stamp}-{uuid.uuid4().hex[:8]}"
    directory = _registry_dir(active_model)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{run_id}.joblib"
    save_artifacts(model, {**report, 'run_id': run_id, 'created_utc': stamp}, path)
    return run_id


def list_runs(active_model: Path) -> list[dict]:
    """Return metadata from locally created report JSON files only."""
    directory = _registry_dir(active_model)
    runs = []
    if directory.exists():
        for p in sorted(directory.glob('run-*.report.json'), reverse=True)[:100]:
            try:
                report = json.loads(p.read_text(encoding='utf-8'))
                runs.append({
                    'run_id': report.get('run_id', p.name.replace('.report.json', '')),
                    'created_utc': report.get('created_utc'),
                    'metrics': report.get('holdout_metrics', {}),
                    'dataset': report.get('dataset', {}),
                    'layers': report.get('model', {}).get('layers', []),
                    'settings': report.get('settings', {}),
                    'software_version': report.get('version'),
                })
            except (ValueError, OSError):
                continue
    if not runs and Path(active_model).exists():
        report = load_report(Path(active_model)) or {}
        runs = [{
            'run_id': 'current', 'created_utc': None,
            'metrics': report.get('holdout_metrics', {}),
            'dataset': report.get('dataset', {}),
            'layers': report.get('model', {}).get('layers', []),
            'settings': report.get('settings', {}),
            'software_version': report.get('version'),
        }]
    return runs


def load_run_report(active_model: Path, run_id: str) -> dict | None:
    if run_id == 'current':
        return load_report(active_model)
    path = _registry_dir(active_model) / f'{run_id}.joblib'
    return load_report(path) if path.exists() else None
